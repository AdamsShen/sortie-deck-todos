export type I18nKey = keyof typeof dict.en;

export function t(lang: Lang, key: I18nKey | string): string {
  const table = dict[lang] ?? dict.en;
  if (key in table) {
    return table[key as I18nKey];
  }
  return dict.en[key as I18nKey] ?? key;
}

export function statusLabel(lang: Lang, s: string): string {
  const map: Record<string, I18nKey> = {
    draft: "discussing",
    running: "running",
    waiting_hitl: "waiting",
    stopped: "failed",
    failed: "failed",
    done: "done",
  };
  return t(lang, map[s] || s);
}

